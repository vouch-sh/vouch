/// Result of a single `try_activate_org_key_rotation` attempt for one `(org,
/// alg)` pair.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) enum ActivateOutcome {
    /// Signing switched: `old_kid` is now Retiring, `new_kid` is now Active.
    Activated { old_kid: String, new_kid: String },
    /// A peer instance already completed this activation; nothing to do.
    AlreadyDone,
    /// The pending key's `activate_at` has not yet elapsed.
    NotDue,
    /// No pending key is staged for this `(org, alg)` pair.
    NothingStaged,
}

