/// Hours to publish a pending successor key before activating it.
///
/// Fixed at 24h (S2 / user decision): larger than the 1h OIDC discovery
/// `max-age` and well above community-reported AWS JWKS cache TTLs, so relying
/// parties will have seen the new `kid` before signing switches to it.
pub(crate) const PUBLISH_AHEAD_HOURS: i64 = 24;

/// Floor for the retirement window in hours (M1).
///
/// Ensures that a reduction of `session_hours` below 8h before rotation does
/// not leave tokens signed by the old key verifiable for longer than the
/// retirement window covers.
const RETIREMENT_FLOOR_HOURS: i64 = 8;

/// Margin added to the retirement window to absorb cache staleness.
///
/// Covers the `ORG_KEYS_CACHE_TTL` (60s) and the OIDC discovery `max-age`
/// (1h), plus a conservative buffer. The window formula is:
/// `activate_at + max(session_hours, RETIREMENT_FLOOR_HOURS) + RETIREMENT_MARGIN_HOURS`.
const RETIREMENT_MARGIN_HOURS: i64 = 2;

/// The issuer an org's federation tokens must use: its claimed subdomain
/// issuer, or the shared base URL when it has no subdomain.
///
/// **Fail-closed:** an org that claimed a subdomain must never fall back to the
/// shared issuer — its tokens would not match its discovery document or the
/// relying party's OIDC provider config. A subdomain that can't be turned into
/// an issuer URL is an error, not a silent downgrade.
///
/// Issuer selection is gated on whether a subdomain is *claimed*, not on
/// at-rest encryption — unlike [`resolve_org_keys`], which yields a per-org
/// signing key only under encryption. These stay consistent because claiming
/// requires an encrypted store (enforced at the claim handler and the startup
/// guard) and `is_encrypted()` is fixed for the life of the process: a claimed
/// subdomain therefore implies per-org keys exist, so the org issuer is always
/// backed by an org-specific key. The one exception — org issuer served under
/// the shared key — requires an out-of-band DB write on a plaintext deployment;
/// [`resolve_org_keys`]'s encryption check is the fail-safe backstop for it.
///
/// # Errors
/// Returns `ServiceError` if a claimed label can't be built into an issuer URL.
pub fn org_issuer_or_base(
    config: &ServerConfig,
    org: Option<&Organization>,
) -> Result<String, ServiceError> {
    if let Some(label) = org.and_then(|o| o.subdomain.as_deref()) {
        config.org_issuer(label).ok_or_else(|| {
            tracing::error!("could not build org issuer for label '{label}' from base_url");
            ServiceError::api(
                StatusCode::INTERNAL_SERVER_ERROR,
                "issuer_error",
                "Failed to construct the organization issuer",
            )
        })
    } else {
        Ok(config.base_url.clone())
    }
}

/// An org's active signing keys — one per algorithm.
///
/// Callers project the field they need (`&keys.es256` / `&keys.rs256`).
pub struct OrgKeys {
    pub es256: OidcSigningKey,
    pub rs256: OidcRsaSigningKey,
}

/// A unified snapshot of an org's full key set, held by [`OrgKeysCache`].
///
/// Both projections (signing and JWKS) derive from the same `list_all("org_id")`
/// result, so the signing key is always in this instance's own published JWKS —
/// no cross-projection staleness within a single server instance (S1 invariant).
pub struct OrgKeySetSnapshot {
    /// Active signers for token issuance — ES256 and RS256.
    pub signers: OrgKeys,
    /// Ordered public JWKs for all live keys (Active + Pending + Retiring).
    ///
    /// Sorted per M2: all RS256 keys first (Active → Pending → Retiring),
    /// then all ES256 keys in the same order. Per OIDC Core §3.1.3.7 RS256
    /// must appear first; within an algorithm the order is deterministic for
    /// stable response bytes and test assertions.
    pub jwks: Vec<Jwk>,
}

/// How long a resolved key set may be served from [`OrgKeysCache`].
const ORG_KEYS_CACHE_TTL: Duration = Duration::from_mins(1);

/// Inner map type for `OrgKeysCache`: org ID → (insert time, snapshot).
type OrgKeysCacheMap = HashMap<String, (Instant, Arc<OrgKeySetSnapshot>)>;

/// Cache of resolved per-org key set snapshots, keyed by org ID.
///
/// The inner `Arc<Mutex<…>>` makes `OrgKeysCache` cheaply cloneable: the
/// background cleanup task and request handlers share the same underlying map
/// so cache invalidations propagate across both.
///
/// Every rotation transition must call `invalidate(org_id)` so the next
/// request after a state change rebuilds from the DB rather than serving a
/// stale snapshot.
#[derive(Default)]
pub struct OrgKeysCache {
    entries: Arc<Mutex<OrgKeysCacheMap>>,
}

impl Clone for OrgKeysCache {
    fn clone(&self) -> Self {
        Self {
            entries: Arc::clone(&self.entries),
        }
    }
}

impl OrgKeysCache {
    /// Return a cached snapshot for `org_id`, if present and not expired.
    fn get(&self, org_id: &str) -> Option<Arc<OrgKeySetSnapshot>> {
        let Ok(map) = self.entries.lock() else {
            return None;
        };
        map.get(org_id)
            .filter(|(inserted_at, _)| inserted_at.elapsed() < ORG_KEYS_CACHE_TTL)
            .map(|(_, snap)| Arc::clone(snap))
    }

    /// Cache `snapshot`, pruning expired entries so deleted orgs don't accumulate.
    fn insert(&self, org_id: &str, snapshot: Arc<OrgKeySetSnapshot>) {
        let Ok(mut map) = self.entries.lock() else {
            return;
        };
        map.retain(|_, (inserted_at, _)| inserted_at.elapsed() < ORG_KEYS_CACHE_TTL);
        map.insert(org_id.to_string(), (Instant::now(), snapshot));
    }

    /// Evict the cached snapshot for `org_id`.
    ///
    /// Called after every rotation transition (stage, activate, reap, emergency)
    /// so the next request rebuilds from the DB immediately rather than serving
    /// a now-stale snapshot.
    pub fn invalidate(&self, org_id: &str) {
        if let Ok(mut map) = self.entries.lock() {
            map.remove(org_id);
        }
    }
}

/// Resolve an org's own signing key set, creating it on first use.
///
/// Returns `None` when the org has no claimed subdomain, or when the document
/// store doesn't encrypt at rest — the caller then falls back to the common
/// platform key. Resolutions are served from a per-org cache for
/// [`ORG_KEYS_CACHE_TTL`], so the token hot paths don't re-read and unseal key
/// rows on every request.
///
/// The returned snapshot also contains the ordered public-JWK list for all live
/// keys (Active + Pending + Retiring) which [`org_jwks`] uses directly.
///
/// # Errors
/// Returns an error if key creation or loading fails.
pub async fn resolve_org_keys(
    state: &Arc<AppState>,
    org: Option<&Organization>,
) -> Result<Option<Arc<OrgKeySetSnapshot>>> {
    let Some(org) = org else { return Ok(None) };
    if org.subdomain.is_none() || !state.store.is_encrypted() {
        return Ok(None);
    }
    if let Some(snap) = state.org_keys_cache.get(&org.id) {
        return Ok(Some(snap));
    }
    let store = &state.store;

    // Single list_all call to check which active keys already exist (P8 —
    // avoids 3 serial round-trips by discovering the full doc set upfront).
    let docs = db::list_org_signing_keys(store, &org.id).await?;
    let needs_es256 = !docs
        .iter()
        .any(|d| d.data.alg == JwsAlgorithm::Es256 && d.data.state == SigningKeyState::Active);
    let needs_rs256 = !docs
        .iter()
        .any(|d| d.data.alg == JwsAlgorithm::Rs256 && d.data.state == SigningKeyState::Active);

    if needs_es256 {
        ensure_es256_key(store, &org.id).await?;
    }
    if needs_rs256 {
        ensure_rs256_key(store, &org.id).await?;
    }

    // Re-read only when we just generated new keys; otherwise build from the
    // already-loaded list (saves the third round-trip in the common case).
    let docs = if needs_es256 || needs_rs256 {
        db::list_org_signing_keys(store, &org.id).await?
    } else {
        docs
    };

    let Some(snap) = build_snapshot(&docs)? else {
        return Ok(None);
    };
    let snap = Arc::new(snap);
    state.org_keys_cache.insert(&org.id, Arc::clone(&snap));
    Ok(Some(snap))
}

/// Build the JWKS served on `org`'s issuer-subdomain host: the org's own keys,
/// or the common keys when the org has none (dev / not-yet-encrypted). RSA
/// first (OIDC Core §3.1.3.7), then EC; within each alg: Active → Pending →
/// Retiring.
///
/// Uses the unified cache snapshot so signing and JWKS are always consistent
/// within an instance (S1 invariant).
///
/// # Errors
/// Returns `ServiceError` if a key cannot be resolved or exported.
pub async fn org_jwks(
    state: &Arc<AppState>,
    org: &Organization,
) -> Result<JwksResponse, ServiceError> {
    let Some(snap) = resolve_org_keys(state, Some(org))
        .await
        .map_err(|e| ServiceError::Internal(format!("resolve org keys: {e}")))?
    else {
        return build_jwks(state);
    };
    Ok(JwksResponse {
        keys: snap.jwks.clone(),
    })
}

/// Create the org's ES256 key if it doesn't exist (current slot).
///
/// Idempotent: the deterministic slot makes a concurrent creation or retry
/// collide on the primary key rather than insert a duplicate.
async fn ensure_es256_key(store: &DocumentStore, org_id: &str) -> Result<()> {
    if db::get_org_signing_key(store, org_id, JwsAlgorithm::Es256)
        .await?
        .is_some()
    {
        return Ok(());
    }
    let der = OidcSigningKey::generate_pkcs8_der().context("ensure ES256: generate DER")?;
    let key = OidcSigningKey::from_pkcs8_der(&der).context("ensure ES256: parse DER")?;
    let doc = OrgSigningKeyDoc {
        org_id: org_id.to_string(),
        alg: JwsAlgorithm::Es256,
        kid: key.key_id().to_string(),
        private_pkcs8_der_b64: STANDARD.encode(&der).into(),
        state: SigningKeyState::Active,
    };
    db::try_insert_org_signing_key(store, &doc).await?;
    Ok(())
}

/// Create the org's RS256 key if it doesn't exist (current slot).
///
/// Offloads RSA-3072 generation (~200ms) to the blocking pool. Idempotent.
async fn ensure_rs256_key(store: &DocumentStore, org_id: &str) -> Result<()> {
    if db::get_org_signing_key(store, org_id, JwsAlgorithm::Rs256)
        .await?
        .is_some()
    {
        return Ok(());
    }
    let der = tokio::task::spawn_blocking(OidcRsaSigningKey::generate_pkcs8_der)
        .await
        .context("ensure RS256: keygen task panicked")??;
    let key = OidcRsaSigningKey::from_pkcs8_der(&der).context("ensure RS256: parse DER")?;
    let doc = OrgSigningKeyDoc {
        org_id: org_id.to_string(),
        alg: JwsAlgorithm::Rs256,
        kid: key.key_id().to_string(),
        private_pkcs8_der_b64: STANDARD.encode(&der).into(),
        state: SigningKeyState::Active,
    };
    db::try_insert_org_signing_key(store, &doc).await?;
    Ok(())
}

/// Decode the DER from an `OrgSigningKeyDoc` into a `Zeroizing<Vec<u8>>`.
fn decode_der(doc: &OrgSigningKeyDoc) -> Result<Zeroizing<Vec<u8>>> {
    Ok(Zeroizing::new(
        STANDARD
            .decode(doc.private_pkcs8_der_b64.expose_secret())
            .context("decode org signing key DER")?,
    ))
}

/// State-priority ordering used for JWKS sort within an algorithm.
fn state_priority(state: &SigningKeyState) -> u8 {
    match state {
        SigningKeyState::Active => 0,
        SigningKeyState::Pending { .. } => 1,
        SigningKeyState::Retiring { .. } => 2,
    }
}

/// Build a unified [`OrgKeySetSnapshot`] from a pre-loaded slice of key docs.
///
/// Finds the Active ES256 and RS256 keys for signing, and builds the sorted
/// public-JWK list for the JWKS endpoint. Returns `None` if no Active key is
/// found for either algorithm.
///
/// **Ordering (M2):** RS256 keys first, then ES256; within each algorithm:
/// Active → Pending → Retiring. This is a hard constraint for OIDC Core
/// §3.1.3.7 compliance (RS256 must appear first).
///
/// Takes pre-loaded docs from the caller (P8 — avoids an extra DB round-trip
/// when `resolve_org_keys` already has the full doc list in hand).
fn build_snapshot(docs: &[Document<OrgSigningKeyDoc>]) -> Result<Option<OrgKeySetSnapshot>> {
    // Separate by alg and sort by state priority within each alg.
    let mut rs256_docs: Vec<_> = docs
        .iter()
        .filter(|d| d.data.alg == JwsAlgorithm::Rs256)
        .collect();
    let mut es256_docs: Vec<_> = docs
        .iter()
        .filter(|d| d.data.alg == JwsAlgorithm::Es256)
        .collect();
    rs256_docs.sort_by_key(|d| state_priority(&d.data.state));
    es256_docs.sort_by_key(|d| state_priority(&d.data.state));

    // Find the active key for each alg — no active key means the org has no
    // live signing capability; return None to fall back to the common key.
    let Some(active_rs256_doc) = rs256_docs
        .iter()
        .find(|d| d.data.state == SigningKeyState::Active)
    else {
        return Ok(None);
    };
    let Some(active_es256_doc) = es256_docs
        .iter()
        .find(|d| d.data.state == SigningKeyState::Active)
    else {
        return Ok(None);
    };

    let rs256_der = decode_der(&active_rs256_doc.data)?;
    let es256_der = decode_der(&active_es256_doc.data)?;
    let rs256 = OidcRsaSigningKey::from_pkcs8_der(&rs256_der)?;
    let es256 = OidcSigningKey::from_pkcs8_der(&es256_der)?;

    // Build public JWKs: RS256 first (all states), then ES256 (all states).
    let mut jwks = Vec::with_capacity(rs256_docs.len().saturating_add(es256_docs.len()));
    for doc in &rs256_docs {
        let der = decode_der(&doc.data)?;
        let key = OidcRsaSigningKey::from_pkcs8_der(&der)?;
        jwks.push(Jwk::Rsa(key.public_key_jwk()?));
    }
    for doc in &es256_docs {
        let der = decode_der(&doc.data)?;
        let key = OidcSigningKey::from_pkcs8_der(&der)?;
        jwks.push(Jwk::Ec(key.public_key_jwk()?));
    }

    Ok(Some(OrgKeySetSnapshot {
        signers: OrgKeys { es256, rs256 },
        jwks,
    }))
}

