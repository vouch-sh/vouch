/// Stage a graceful key rotation for an organization.
///
/// Generates successor keys for **both** ES256 and RS256 (N1 — a key-store
/// compromise exposes both DERs), writes them to the next-slot with state
/// [`SigningKeyState::Pending`] and `activate_at = now + PUBLISH_AHEAD_HOURS`,
/// and publishes them immediately in the org JWKS so relying parties can cache
/// the new `kid` before signing switches.
///
/// Idempotent: if both next-slots already exist, returns `Ok(false)` without
/// emitting any DB writes. Returns `Ok(true)` when at least one new key was
/// staged. Callers can use the bool to suppress a redundant audit event when the
/// operator clicks "Rotate" while a rotation is already in progress (C6).
///
/// Invalidates the org's cache entry so the next JWKS response includes the
/// new Pending keys without waiting for the 60s TTL (I3 / S1 invariant).
///
/// # Errors
/// Returns an error if key generation or the DB insert fails.
pub async fn stage_org_key_rotation(
    store: &DocumentStore,
    org_id: &str,
    cache: &OrgKeysCache,
) -> Result<bool> {
    // Check next-slot occupancy before generating keys (L2 / S1).
    // RSA-3072 keygen takes ~200ms on the blocking pool; skip it when the
    // slot is already occupied. This is a courtesy check — `stage_one_alg`
    // is still idempotent if a concurrent writer races between the read and
    // the insert: the no-op `try_insert_org_signing_key_next` absorbs it.
    let es256_occupied = db::get_org_signing_key_next(store, org_id, JwsAlgorithm::Es256)
        .await?
        .is_some();
    let rs256_occupied = db::get_org_signing_key_next(store, org_id, JwsAlgorithm::Rs256)
        .await?
        .is_some();

    if es256_occupied && rs256_occupied {
        // Both pending — already staged; invalidate in case the cache is stale.
        cache.invalidate(org_id);
        return Ok(false);
    }

    // Generate only the missing key material.
    let rs256_der = if !rs256_occupied {
        Some(
            tokio::task::spawn_blocking(OidcRsaSigningKey::generate_pkcs8_der)
                .await
                .context("stage: RS256 keygen task panicked")??,
        )
    } else {
        None
    };
    let es256_der = if !es256_occupied {
        Some(OidcSigningKey::generate_pkcs8_der().context("stage: ES256 keygen")?)
    } else {
        None
    };

    // On a partial-failure retry (ES256 staged, RS256 failed or vice versa),
    // reuse the already-staged alg's activate_at so both algs activate together
    // (C2 — preserves N1 atomicity intent on retry). Fall back to now +
    // PUBLISH_AHEAD_HOURS when neither slot is occupied (the common case).
    let activate_at = if es256_occupied {
        // ES256 is staged — read its activate_at to sync RS256.
        db::get_org_signing_key_next(store, org_id, JwsAlgorithm::Es256)
            .await?
            .and_then(|d| {
                if let SigningKeyState::Pending { activate_at } = d.data.state {
                    Some(activate_at)
                } else {
                    None
                }
            })
            .unwrap_or_else(|| {
                Timestamp::now()
                    .checked_add(Span::new().hours(PUBLISH_AHEAD_HOURS))
                    .unwrap_or_else(|_| Timestamp::now())
            })
    } else if rs256_occupied {
        // RS256 is staged — read its activate_at to sync ES256.
        db::get_org_signing_key_next(store, org_id, JwsAlgorithm::Rs256)
            .await?
            .and_then(|d| {
                if let SigningKeyState::Pending { activate_at } = d.data.state {
                    Some(activate_at)
                } else {
                    None
                }
            })
            .unwrap_or_else(|| {
                Timestamp::now()
                    .checked_add(Span::new().hours(PUBLISH_AHEAD_HOURS))
                    .unwrap_or_else(|_| Timestamp::now())
            })
    } else {
        Timestamp::now()
            .checked_add(Span::new().hours(PUBLISH_AHEAD_HOURS))
            .context("stage: activate_at timestamp overflow")?
    };

    if let Some(ref der) = es256_der {
        stage_one_alg(store, org_id, JwsAlgorithm::Es256, der, activate_at).await?;
    }
    if let Some(ref der) = rs256_der {
        stage_one_alg(store, org_id, JwsAlgorithm::Rs256, der, activate_at).await?;
    }

    // Invalidate so the next JWKS response immediately includes the Pending keys.
    cache.invalidate(org_id);
    Ok(true)
}

/// Stage one algorithm's successor key in the next-slot for `org_id`.
///
/// Called twice by [`stage_org_key_rotation`] (ES256 then RS256). Idempotent:
/// `try_insert_org_signing_key_next` silently skips if the slot already exists.
async fn stage_one_alg(
    store: &DocumentStore,
    org_id: &str,
    alg: JwsAlgorithm,
    der: &[u8],
    activate_at: Timestamp,
) -> Result<()> {
    let kid = match alg {
        JwsAlgorithm::Es256 => OidcSigningKey::from_pkcs8_der(der)
            .context("stage ES256: parse DER")?
            .key_id()
            .to_string(),
        JwsAlgorithm::Rs256 => OidcRsaSigningKey::from_pkcs8_der(der)
            .context("stage RS256: parse DER")?
            .key_id()
            .to_string(),
        other => anyhow::bail!("stage_one_alg: unsupported algorithm {other:?}"),
    };
    let doc = OrgSigningKeyDoc {
        org_id: org_id.to_string(),
        alg,
        kid,
        private_pkcs8_der_b64: STANDARD.encode(der).into(),
        state: SigningKeyState::Pending { activate_at },
    };
    db::try_insert_org_signing_key_next(store, &doc).await?;
    Ok(())
}

// ---------------------------------------------------------------------------
// Graceful rotation — activate (S3 pseudocode)
// ---------------------------------------------------------------------------

/// Try to activate a staged key rotation for one `(org_id, alg)` pair.
///
/// Implements the CAS-first OCC pattern from the rev-B spec (S3): every
/// terminal branch returns `Ok(..)` *before* any write, and CAS-loss is the
/// only `Err(OccConflict)` exit. This prevents `with_dsql_retry!` from spinning
/// on an already-completed activation.
///
/// DSQL commit-abort errors surface through `OrgRotationError::Other`; the
/// `RetryableError` impl delegates to `is_retryable_db_error` so they also
/// loop (N3).
pub(crate) async fn try_activate_org_key_rotation(
    store: &DocumentStore,
    org_id: &str,
    alg: JwsAlgorithm,
    session_hours: u64,
) -> Result<ActivateOutcome, OrgRotationError> {
    crate::with_dsql_retry!(async {
        let mut tx = store.begin().await?;

        // ---- terminal short-circuits: decided BEFORE any write, return Ok(..) ----

        let next_id = db::deterministic_org_key_next_id(org_id, alg);
        let Some(next_doc) = tx.get::<OrgSigningKeyDoc>(&next_id).await? else {
            // No staged key (or already consumed by a peer instance).
            return Ok(ActivateOutcome::NothingStaged);
        };

        let SigningKeyState::Pending { activate_at } = next_doc.data.state else {
            // Staged key is not in Pending state (shouldn't happen in well-formed DB).
            return Ok(ActivateOutcome::AlreadyDone);
        };

        if activate_at > Timestamp::now() {
            return Ok(ActivateOutcome::NotDue);
        }

        let current_id = db::deterministic_org_key_id(org_id, alg);
        let Some(current_doc) = tx.get::<OrgSigningKeyDoc>(&current_id).await? else {
            // No active key; treat as already done (shouldn't happen).
            return Ok(ActivateOutcome::AlreadyDone);
        };

        // If the previous slot is occupied, another activation is still in its
        // retirement window — treat as done and let reaping clear the predecessor.
        let prev_id = db::deterministic_org_key_previous_id(org_id, alg);
        if tx.get::<OrgSigningKeyDoc>(&prev_id).await?.is_some() {
            return Ok(ActivateOutcome::AlreadyDone);
        }

        // Capture predecessor material BEFORE the CAS overwrites the current slot.
        let old_kid = current_doc.data.kid.clone();
        let new_kid = next_doc.data.kid.clone();
        let current_version = current_doc.version;

        // Compute retirement window (M1): floor at RETIREMENT_FLOOR_HOURS so a
        // session_hours reduction before rotation doesn't under-cover existing tokens.
        let session_h = i64::try_from(session_hours).unwrap_or(RETIREMENT_FLOOR_HOURS);
        let retire_hours = session_h.max(RETIREMENT_FLOOR_HOURS);
        let not_after = activate_at
            .checked_add(Span::new().hours(retire_hours.saturating_add(RETIREMENT_MARGIN_HOURS)))
            .map_err(|e| OrgRotationError::Other(anyhow::Error::new(e)))?;

        // Build the new Active doc (successor content, Active state).
        let new_active = OrgSigningKeyDoc {
            state: SigningKeyState::Active,
            ..next_doc.data.clone()
        };
        // Build the Retiring doc (predecessor content, Retiring state).
        let retiring = OrgSigningKeyDoc {
            state: SigningKeyState::Retiring { not_after },
            ..current_doc.data.clone()
        };

        // ---- CAS is the single serialization gate; losers stop here ----
        if !tx
            .compare_and_update(&current_id, current_version, &new_active)
            .await?
        {
            // Version bumped by a peer: retry → re-read → NothingStaged / AlreadyDone.
            return Err(OrgRotationError::OccConflict);
        }

        // Sole winner past this point: prev was confirmed absent, so the insert
        // cannot collide with a concurrent activation (CAS-first ordering).
        tx.insert_with_id(&prev_id, &retiring).await?;
        tx.delete(&next_id).await?;

        tx.commit().await.map_err(OrgRotationError::Other)?;

        Ok(ActivateOutcome::Activated { old_kid, new_kid })
    })
}

