/// Reap an expired Retiring key for one `(org_id, alg)` pair.
///
/// Deletes the previous-slot document if it exists and its `not_after` has
/// elapsed. Emits an `org_issuer_key_reaped` audit event. Invalidates the cache
/// so the deleted key is no longer served in the JWKS.
///
/// Returns `true` if a key was reaped, `false` if the slot was empty or not yet
/// due.
///
/// # Errors
/// Returns an error if the DB delete fails.
pub(crate) async fn reap_org_retired_key(
    store: &DocumentStore,
    org_id: &str,
    alg: JwsAlgorithm,
    audit: &AuditStore,
    cache: &OrgKeysCache,
) -> Result<bool> {
    let prev_id = db::deterministic_org_key_previous_id(org_id, alg);
    let Some(doc) = store.get::<OrgSigningKeyDoc>(&prev_id).await? else {
        return Ok(false);
    };
    let SigningKeyState::Retiring { not_after } = doc.data.state else {
        return Ok(false);
    };
    if not_after > Timestamp::now() {
        return Ok(false);
    }

    let reaped_kid = doc.data.kid.clone();
    store.delete(&prev_id).await?;
    cache.invalidate(org_id);

    let event = serde_json::json!({
        "action": "reap_org_issuer_key",
        "org_id": org_id,
        "alg": alg.as_str(),
        "kid": reaped_kid,
    });
    if let Err(e) = audit
        .insert_event("org_issuer_key_reaped", None, None, &event.to_string())
        .await
    {
        tracing::warn!(error = %e, "failed to write org_issuer_key_reaped audit event");
    }
    Ok(true)
}

// ---------------------------------------------------------------------------
// Cleanup loop — process all pending transitions (M3)
// ---------------------------------------------------------------------------

/// Process pending key-rotation activations and reapings for all organizations.
///
/// Called from the background cleanup loop. Scans all signing-key documents,
/// then for each org:
/// - Activates any Pending keys whose `activate_at` has elapsed (both algs).
/// - Reaps any Retiring keys whose `not_after` has elapsed (both algs).
///
/// Uses `session_hours` from the config to compute the retirement window (M1).
///
/// Per-org failures are logged and skipped so one bad org doesn't abort the
/// whole pass.
///
/// # Errors
/// Returns an error only if the initial scan fails.
pub async fn process_pending_org_key_transitions(
    store: &DocumentStore,
    audit: &AuditStore,
    cache: &OrgKeysCache,
    session_hours: u64,
) -> Result<()> {
    let all_docs = store.list_all::<OrgSigningKeyDoc>().await?;
    let now = Timestamp::now();

    let mut pending_due: Vec<(String, JwsAlgorithm)> = Vec::new();
    let mut retiring_due: Vec<(String, JwsAlgorithm)> = Vec::new();

    for doc in &all_docs {
        match &doc.data.state {
            SigningKeyState::Pending { activate_at } if *activate_at <= now => {
                pending_due.push((doc.data.org_id.clone(), doc.data.alg));
            }
            SigningKeyState::Retiring { not_after } if *not_after <= now => {
                retiring_due.push((doc.data.org_id.clone(), doc.data.alg));
            }
            _ => {}
        }
    }

    for (org_id, alg) in pending_due {
        // try_activate_org_key_rotation contains its own with_dsql_retry! loop.
        match try_activate_org_key_rotation(store, &org_id, alg, session_hours).await {
            Ok(ActivateOutcome::Activated { old_kid, new_kid }) => {
                cache.invalidate(&org_id);
                tracing::info!(
                    org_id,
                    alg = alg.as_str(),
                    old_kid,
                    new_kid,
                    "activated org issuer key"
                );
                let event = serde_json::json!({
                    "action": "activate_org_issuer_key",
                    "org_id": org_id,
                    "alg": alg.as_str(),
                    "old_kid": old_kid,
                    "new_kid": new_kid,
                });
                if let Err(e) = audit
                    .insert_event("org_issuer_key_activated", None, None, &event.to_string())
                    .await
                {
                    tracing::warn!(
                        error = %e,
                        "failed to write org_issuer_key_activated audit event"
                    );
                }
            }
            Ok(_) => {} // NothingStaged / AlreadyDone / NotDue — silent
            Err(e) => {
                tracing::warn!(
                    error = %e,
                    org_id,
                    alg = alg.as_str(),
                    "failed to activate org issuer key"
                );
            }
        }
    }

    for (org_id, alg) in retiring_due {
        if let Err(e) = reap_org_retired_key(store, &org_id, alg, audit, cache).await {
            tracing::warn!(
                error = %e,
                org_id,
                alg = alg.as_str(),
                "failed to reap retired org issuer key"
            );
        }
    }

    Ok(())
}

