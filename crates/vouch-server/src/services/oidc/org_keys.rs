/// Emergency key rotation for an organization.
///
/// Rotates **both** ES256 and RS256 in a **single atomic transaction**.
/// Both successors are generated outside the retry loop (RSA keygen takes
/// ~200ms). If either CAS fails the entire transaction retries atomically;
/// there is no partial-rotation window where one alg is rotated and the other
/// is not.
///
/// The cache is invalidated only after the transaction commits, so this instance
/// never serves a stale snapshot of a key that was already rotated in the DB.
/// If the function returns `Err` (retry budget exhausted), the DB is unchanged
/// and the cache is unmodified.
///
/// Outstanding tokens signed by the compromised key will fail verification until
/// relying parties refetch the JWKS (cross-instance ≤ 60s, downstream ≤ 1h).
/// This breakage is accepted (Q3).
///
/// # Errors
/// Returns an error if key generation or the DB operation fails after the retry
/// budget is exhausted.
pub async fn emergency_rotate_org_keys(
    store: &DocumentStore,
    org_id: &str,
    audit: &AuditStore,
    cache: &OrgKeysCache,
    user_id: Option<&str>,
    email: Option<&str>,
) -> Result<()> {
    // Generate both successors OUTSIDE the retry loop (N4).
    let rs256_der = tokio::task::spawn_blocking(OidcRsaSigningKey::generate_pkcs8_der)
        .await
        .context("emergency: RS256 keygen task panicked")??;
    let es256_der = OidcSigningKey::generate_pkcs8_der().context("emergency: ES256 keygen")?;

    // Parse kids outside the retry loop — cheap and deterministic from the DER.
    let es256_kid = OidcSigningKey::from_pkcs8_der(&es256_der)
        .context("emergency ES256: parse kid")?
        .key_id()
        .to_string();
    let rs256_kid = OidcRsaSigningKey::from_pkcs8_der(&rs256_der)
        .context("emergency RS256: parse kid")?
        .key_id()
        .to_string();

    // Single retry loop: both algs in one transaction — atomicity across algs (I1).
    let result: Result<(String, String), OrgRotationError> = crate::with_dsql_retry!(async {
        let mut tx = store.begin().await?;

        // Read and CAS the ES256 current slot.
        let es256_current_id = db::deterministic_org_key_id(org_id, JwsAlgorithm::Es256);
        let Some(es256_current) = tx.get::<OrgSigningKeyDoc>(&es256_current_id).await? else {
            return Err(OrgRotationError::Other(anyhow::anyhow!(
                "emergency: no current ES256 key for org '{org_id}'"
            )));
        };
        let old_es256_kid = es256_current.data.kid.clone();
        let es256_version = es256_current.version;

        // Read and CAS the RS256 current slot.
        let rs256_current_id = db::deterministic_org_key_id(org_id, JwsAlgorithm::Rs256);
        let Some(rs256_current) = tx.get::<OrgSigningKeyDoc>(&rs256_current_id).await? else {
            return Err(OrgRotationError::Other(anyhow::anyhow!(
                "emergency: no current RS256 key for org '{org_id}'"
            )));
        };
        let old_rs256_kid = rs256_current.data.kid.clone();
        let rs256_version = rs256_current.version;

        // Build replacement Active docs.
        let new_es256 = OrgSigningKeyDoc {
            org_id: org_id.to_string(),
            alg: JwsAlgorithm::Es256,
            kid: es256_kid.clone(),
            private_pkcs8_der_b64: STANDARD.encode(&*es256_der).into(),
            state: SigningKeyState::Active,
        };
        let new_rs256 = OrgSigningKeyDoc {
            org_id: org_id.to_string(),
            alg: JwsAlgorithm::Rs256,
            kid: rs256_kid.clone(),
            private_pkcs8_der_b64: STANDARD.encode(&*rs256_der).into(),
            state: SigningKeyState::Active,
        };

        // CAS both slots. Either version mismatch retries the whole transaction.
        if !tx
            .compare_and_update(&es256_current_id, es256_version, &new_es256)
            .await?
        {
            return Err(OrgRotationError::OccConflict);
        }
        if !tx
            .compare_and_update(&rs256_current_id, rs256_version, &new_rs256)
            .await?
        {
            return Err(OrgRotationError::OccConflict);
        }

        // Delete side slots for both algs outright (S4) — removes compromised key
        // material from the JWKS build immediately after this commit.
        tx.delete(&db::deterministic_org_key_previous_id(
            org_id,
            JwsAlgorithm::Es256,
        ))
        .await?;
        tx.delete(&db::deterministic_org_key_next_id(
            org_id,
            JwsAlgorithm::Es256,
        ))
        .await?;
        tx.delete(&db::deterministic_org_key_previous_id(
            org_id,
            JwsAlgorithm::Rs256,
        ))
        .await?;
        tx.delete(&db::deterministic_org_key_next_id(
            org_id,
            JwsAlgorithm::Rs256,
        ))
        .await?;

        tx.commit().await.map_err(OrgRotationError::Other)?;

        Ok((old_es256_kid, old_rs256_kid))
    });

    let (old_es256_kid, old_rs256_kid) = result.map_err(anyhow::Error::from)?;

    // Invalidate cache after the atomic transaction commits — both algs rotated.
    cache.invalidate(org_id);

    // Emit one audit event per algorithm. Including operator identity (user_id /
    // email) here makes the per-alg events the sole canonical audit trail for an
    // emergency rotation — no separate handler-level event is needed (C1).
    let es256_event = serde_json::json!({
        "action": "emergency_rotate_org_issuer_key",
        "org_id": org_id,
        "alg": JwsAlgorithm::Es256.as_str(),
        "old_kid": old_es256_kid,
        "new_kid": es256_kid,
    });
    if let Err(e) = audit
        .insert_event(
            "org_issuer_key_emergency_rotation",
            user_id,
            email,
            &es256_event.to_string(),
        )
        .await
    {
        tracing::warn!(
            error = %e,
            "failed to write org_issuer_key_emergency_rotation (ES256) audit event"
        );
    }
    let rs256_event = serde_json::json!({
        "action": "emergency_rotate_org_issuer_key",
        "org_id": org_id,
        "alg": JwsAlgorithm::Rs256.as_str(),
        "old_kid": old_rs256_kid,
        "new_kid": rs256_kid,
    });
    if let Err(e) = audit
        .insert_event(
            "org_issuer_key_emergency_rotation",
            user_id,
            email,
            &rs256_event.to_string(),
        )
        .await
    {
        tracing::warn!(
            error = %e,
            "failed to write org_issuer_key_emergency_rotation (RS256) audit event"
        );
    }

    tracing::warn!(org_id, "emergency org issuer key rotation completed");
    Ok(())
}

