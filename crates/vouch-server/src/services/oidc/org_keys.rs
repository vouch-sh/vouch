    /// Verify that the resolver uses the Active slot's key for signing, not a
    /// Pending key.  After a stage the snapshot signer's kid must still match
    /// the current (Active) document, not the staged (Pending) next-slot.
    #[tokio::test]
    async fn resolver_signs_with_active_key_only() {
        let (state, org_id) = setup_encrypted_with_subdomain().await;
        let org = crate::db::get_organization(&state.store, &org_id)
            .await
            .unwrap()
            .unwrap();

        // First resolve creates the Active keys.
        let snap_before = resolve_org_keys(&state, Some(&org)).await.unwrap().unwrap();

        // Read the Active ES256 document to get its kid.
        let active_doc = get_org_signing_key(&state.store, &org_id, JwsAlgorithm::Es256)
            .await
            .unwrap()
            .unwrap();
        let active_kid = active_doc.data.kid.clone();

        // Stage rotation — inserts a Pending key with a future activate_at and
        // invalidates the cache (so the next resolve sees the Pending in JWKS).
        stage_org_key_rotation(&state.store, &org_id, &state.org_keys_cache)
            .await
            .unwrap();

        // Resolve again — must sign with the still-Active key, not the Pending one.
        let snap_after = resolve_org_keys(&state, Some(&org)).await.unwrap().unwrap();
        let signer_kid = snap_after.signers.es256.key_id().to_string();
        assert_eq!(
            signer_kid, active_kid,
            "resolver must sign with Active key (kid={active_kid}), \
             not the Pending successor after stage"
        );

        // The JWKS grows from 2 to 4 (Active+Pending for each alg) but the
        // kid for the before-snapshot signer must still appear in the JWKS.
        let before_kid = snap_before.signers.es256.key_id().to_string();
        let ec_kids: Vec<&str> = snap_after
            .jwks
            .iter()
            .filter_map(|jwk| {
                if let Jwk::Ec(ec) = jwk {
                    Some(ec.kid.as_str())
                } else {
                    None
                }
            })
            .collect();
        assert!(
            ec_kids.contains(&before_kid.as_str()),
            "Active key kid {before_kid} must still appear in JWKS after stage"
        );
    }

    /// Verify M2: RS256 JWKs precede ES256 JWKs in the ordered snapshot, and
    /// all kids across the full JWKS are distinct.
    #[tokio::test]
    async fn jwks_rsa_first_and_all_kids_distinct() {
        let (state, org_id) = setup_encrypted_with_subdomain().await;
        let org = crate::db::get_organization(&state.store, &org_id)
            .await
            .unwrap()
            .unwrap();

        resolve_org_keys(&state, Some(&org)).await.unwrap();
        // Stage so both algs have 2 keys (Active + Pending = 4 total).
        // stage_org_key_rotation invalidates the cache — no manual call needed.
        stage_org_key_rotation(&state.store, &org_id, &state.org_keys_cache)
            .await
            .unwrap();

        let snap = resolve_org_keys(&state, Some(&org)).await.unwrap().unwrap();
        assert_eq!(
            snap.jwks.len(),
            4,
            "expected 4 JWKs after stage (2 RS256 + 2 ES256)"
        );

        // M2: all Rsa JWKs must precede all Ec JWKs.
        let mut saw_ec = false;
        for jwk in &snap.jwks {
            match jwk {
                Jwk::Rsa(_) => assert!(
                    !saw_ec,
                    "M2 violation: RSA JWK appears after an EC JWK in the JWKS"
                ),
                Jwk::Ec(_) => saw_ec = true,
            }
        }
        assert!(saw_ec, "at least one EC JWK must be present");

        // All kids must be distinct.
        let kids: Vec<&str> = snap
            .jwks
            .iter()
            .map(|jwk| match jwk {
                Jwk::Rsa(rsa) => rsa.kid.as_str(),
                Jwk::Ec(ec) => ec.kid.as_str(),
            })
            .collect();
        let unique: std::collections::HashSet<&str> = kids.iter().copied().collect();
        assert_eq!(
            kids.len(),
            unique.len(),
            "JWKS contains duplicate kids: {kids:?}"
        );
    }

    /// M1 floor: when session_hours < RETIREMENT_FLOOR_HOURS, the retirement
    /// window uses the floor so tokens minted under a short session cap are
    /// still covered by the old key being present in the JWKS.
    #[tokio::test]
    async fn schedule_math_m1_floor_applies_when_session_hours_is_below_8() {
        let (state, org_id) = setup_encrypted_with_subdomain().await;
        let org = crate::db::get_organization(&state.store, &org_id)
            .await
            .unwrap()
            .unwrap();
        resolve_org_keys(&state, Some(&org)).await.unwrap();

        // Insert a pending ES256 key with activate_at in the past so the
        // activation fires immediately.
        let activate_at = Timestamp::now()
            .checked_sub(Span::new().seconds(1))
            .unwrap();
        let der = OidcSigningKey::generate_pkcs8_der().unwrap();
        let kid = OidcSigningKey::from_pkcs8_der(&der)
            .unwrap()
            .key_id()
            .to_string();
        let pending_doc = OrgSigningKeyDoc {
            org_id: org_id.clone(),
            alg: JwsAlgorithm::Es256,
            kid,
            private_pkcs8_der_b64: STANDARD.encode(&*der).into(),
            state: SigningKeyState::Pending { activate_at },
        };
        try_insert_org_signing_key_next(&state.store, &pending_doc)
            .await
            .unwrap();

        // Activate with session_hours=1 (below the 8h floor).
        let outcome = try_activate_org_key_rotation(&state.store, &org_id, JwsAlgorithm::Es256, 1)
            .await
            .unwrap();
        assert!(
            matches!(outcome, ActivateOutcome::Activated { .. }),
            "expected Activated, got {outcome:?}"
        );

        // The retiring key's not_after must be >= activate_at + (floor + margin).
        let floor_window = RETIREMENT_FLOOR_HOURS.saturating_add(RETIREMENT_MARGIN_HOURS);
        let min_not_after = activate_at
            .checked_add(Span::new().hours(floor_window))
            .unwrap();

        let retiring = get_org_signing_key_previous(&state.store, &org_id, JwsAlgorithm::Es256)
            .await
            .unwrap()
            .expect("retiring key must occupy the previous slot after activation");
        let SigningKeyState::Retiring { not_after } = retiring.data.state else {
            panic!("previous slot must be in Retiring state after activation");
        };
        assert!(
            not_after >= min_not_after,
            "not_after ({not_after}) must be >= activate_at + {floor_window}h ({min_not_after})"
        );
    }

